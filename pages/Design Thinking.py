def read_api_key(environment_name, secret_name):
    key = os.environ.get(environment_name, "").strip()
    if key:
        return key
    try:
        value = st.secrets.get(secret_name, "")
        return value.strip() if isinstance(value, str) else ""
    except Exception:
        # The page remains usable before deployment secrets have been configured.
        return ""


def safe_text(value):
    return html.escape(str(value or ""), quote=True)


def lens_cards(report=None):
    cards = []
    for index, (key, lens) in enumerate(LENSES.items(), start=1):
        result = (report or {}).get("lenses", {}).get(key)
        detail = lens["subtitle"]
        badge = ""
        if result:
            signal = result.get("signal", "Unknown")
            signal_class = {
                "Promising": "promising", "Mixed": "mixed", "Concern": "concern"
            }.get(signal, "unknown")
            badge = (
                f'<span class="dt-signal dt-signal--{signal_class}">{safe_text(signal)}</span>'
                f'<span class="dt-confidence">Evidence confidence: '
                f'{safe_text(result.get("confidence", "Low"))}</span>'
            )
        cards.append(
            f'<article class="dt-lens dt-lens--{key}">'
            f'<span class="dt-lens-number">0{index}</span>'
            f'<h3>{safe_text(lens["title"])}</h3><p>{safe_text(detail)}</p>'
            f'{badge}</article>'
        )
    st.markdown('<div class="dt-lenses">' + "".join(cards) + "</div>", unsafe_allow_html=True)


def source_links(source_ids, source_index):
    links = []
    for source_id in source_ids:
        source = source_index.get(source_id)
        if source and urlparse(source.get("url", "")).scheme in ("http", "https"):
            # Source IDs are generated by the backend, never by retrieved pages.
            url = source["url"].replace("(", "%28").replace(")", "%29")
            links.append(f"[{source_id}]({url})")
    return " · ".join(links)


def render_brief(brief):
    for field in INPUT_FIELDS:
        if brief.get(field):
            st.markdown(f"**{INPUT_LABELS[field]}**")
            st.write(brief[field])


def render_lens(lens_key, result, source_index):
    lens = LENSES[lens_key]
    st.subheader(lens["title"])
    st.write(result["summary"])
    st.caption(
        f"Signal: {result['signal']} · Evidence confidence: {result['confidence']}. "
        "Confidence reflects the available evidence, not the idea’s probability of success."
    )
    answers = {item["id"]: item for item in result["questions"]}
    for question in lens["questions"]:
        answer = answers.get(question["id"], {})
        with st.expander(f"{question['id']} · {question['question']}", expanded=True):
            st.caption(answer.get("basis", "Hypothesis"))
            st.write(answer.get("answer", "This question needs further investigation."))
            links = source_links(answer.get("source_ids", []), source_index)
            if links:
                st.markdown("**Sources:** " + links)
            if answer.get("gap"):
                st.markdown("**What still needs to be learned**")
                st.write(answer["gap"])
    with st.container(border=True):
        st.markdown("**The assumption to test**")
        st.write(result["critical_assumption"])


def render_experiment(lens_key, result, first=False):
    experiment = result["experiment"]
    title = LENSES[lens_key]["title"]
    with st.container(border=True):
        st.caption("START HERE" if first else "THEN TEST")
        st.subheader(f"{title}: {experiment['method']}")
        st.markdown("**Hypothesis**")
        st.write(experiment["hypothesis"])
        left, right = st.columns(2)
        with left:
            st.markdown("**Who / what to test**")
            st.write(experiment["participants"])
            st.markdown("**Measure**")
            st.write(experiment["metric"])
        with right:
            st.markdown("**Continue if**")
            st.write(experiment["pass_threshold"])
            st.markdown("**Reconsider if**")
            st.write(experiment["fail_signal"])
        st.caption("Suggested timebox: " + experiment["timebox"])


def prepare_downloads(report):
    signature = hashlib.sha256(
        json.dumps(report, sort_keys=True, ensure_ascii=False).encode("utf-8")
    ).hexdigest()
    cached = st.session_state.get("dt_downloads", {})
    if cached.get("signature") != signature:
        cached = {
            "signature": signature,
            "markdown": to_markdown(report).encode("utf-8"),
            "pdf": None,
        }
        try:
            cached["pdf"] = build_pdf(report)
        except Exception:
            # An export error must never hide the completed evaluation.
            pass
        st.session_state["dt_downloads"] = cached
    return cached


